def get_topics():
    topics = []
    for i, t in enumerate(TOPICS):
        icon = t.get('icon', '')
        if icon not in ICONS:
            icon = ICON_ORDER[i % len(ICON_ORDER)]
        topics.append({
            'title': t['title'],
            'description': t['description'],
            'booking_topic': t.get('booking_topic') or t['title'],
            'icon_path': ICONS[icon],
        })
    return topics
